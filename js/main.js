// ---------- Filtro interativo de projetos por tag ----------
(function projectFilter() {
  const chips = document.querySelectorAll('.filter-chip');
  const items = document.querySelectorAll('#projGrid .proj-item');
  const empty = document.getElementById('filterEmpty');
  if (!chips.length) return;

  chips.forEach(chip => {
    chip.addEventListener('click', () => {
      chips.forEach(c => c.classList.remove('active'));
      chip.classList.add('active');
      const filter = chip.dataset.filter;

      let visibleCount = 0;
      items.forEach(item => {
        const match = filter === 'ALL' || item.dataset.tag === filter;
        item.classList.toggle('filtered-out', !match);
        if (match) visibleCount++;
      });

      if (empty) empty.style.display = visibleCount === 0 ? 'block' : 'none';
    });
  });
})();

// ---------- Command palette (terminal de navegação) ----------
(function commandPalette() {
  const overlay = document.getElementById('cmdk');
  const input = document.getElementById('cmdkInput');
  const output = document.getElementById('cmdkOutput');
  const trigger = document.getElementById('cmdkTrigger');
  if (!overlay || !input || !output) return;

  function open() {
    overlay.classList.add('open');
    input.value = '';
    input.focus();
  }
  function close() {
    overlay.classList.remove('open');
  }

  document.addEventListener('keydown', (e) => {
    const typing = ['INPUT', 'TEXTAREA'].includes(document.activeElement.tagName);
    if (e.key === '/' && !typing) {
      e.preventDefault();
      open();
    } else if (e.key === 'Escape') {
      close();
    }
  });

  trigger.addEventListener('click', open);
  overlay.addEventListener('click', (e) => { if (e.target === overlay) close(); });

  const commands = {
    help: () => 'comandos: sobre · projetos · stack · certificacoes · jornada · contato · skills · whoami · github · linkedin · tema · idioma · sudo hire juan · clear',
    sobre: () => { location.hash = '#about'; close(); return 'navegando para #about...'; },
    about: () => commands.sobre(),
    projetos: () => { location.hash = '#projects'; close(); return 'navegando para #projects...'; },
    projects: () => commands.projetos(),
    stack: () => { location.hash = '#stack'; close(); return 'navegando para #stack...'; },
    certificacoes: () => { location.hash = '#certs'; close(); return 'navegando para #certs...'; },
    certifications: () => commands.certificacoes(),
    certs: () => commands.certificacoes(),
    jornada: () => { location.hash = '#cv'; close(); return 'navegando para #cv...'; },
    cv: () => commands.jornada(),
    contato: () => { location.hash = '#contact'; close(); return 'navegando para #contact...'; },
    contact: () => commands.contato(),
    skills: () => 'Python · PowerShell · Docker · CI/CD · Hyper-V · Fortinet · Linux · Bash · OCI · Google Cloud · Azure · AWS',
    whoami: () => 'juan verdan · devops engineer & automação',
    github: () => { window.open('https://github.com/juanverdan', '_blank'); return 'abrindo github.com/juanverdan ↗'; },
    linkedin: () => { window.open('https://www.linkedin.com/in/juanverdan/', '_blank'); return 'abrindo linkedin ↗'; },
    tema: () => { document.getElementById('themeToggle').click(); return 'tema alternado.'; },
    theme: () => commands.tema(),
    idioma: () => { setLanguage(currentLang === 'pt' ? 'en' : 'pt'); return 'idioma alternado.'; },
    language: () => commands.idioma(),
    'sudo hire juan': () => { location.hash = '#contact'; close(); return 'permissão concedida. redirecionando...'; },
    clear: () => { output.innerHTML = ''; return null; },
    exit: () => { close(); return null; },
  };

  input.addEventListener('keydown', (e) => {
    if (e.key !== 'Enter') return;
    const raw = input.value.trim();
    if (!raw) return;
    const line = document.createElement('div');
    line.className = 'cmdk-line';
    line.innerHTML = `<span class="cmdk-prompt">$</span> ${raw}`;
    output.appendChild(line);

    const fn = commands[raw.toLowerCase()];
    const result = fn ? fn() : `comando não encontrado: ${raw} — digite "help"`;
    if (result) {
      const res = document.createElement('div');
      res.className = 'cmdk-result';
      res.textContent = result;
      output.appendChild(res);
    }
    output.scrollTop = output.scrollHeight;
    input.value = '';
  });
})();

