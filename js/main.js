// ---------- Contadores animados nas estatísticas ----------
(function animateCounters() {
  if (prefersReducedMotion) return;
  const counterObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      counterObserver.unobserve(entry.target);
      const el = entry.target;
      const match = el.textContent.trim().match(/^(\d+)(.*)$/);
      if (!match) return;
      const target = parseInt(match[1], 10);
      const suffix = match[2];
      const start = performance.now();
      const duration = 900;

      function tick(now) {
        const p = Math.min((now - start) / duration, 1);
        const eased = 1 - Math.pow(1 - p, 3);
        el.textContent = Math.round(eased * target) + suffix;
        if (p < 1) requestAnimationFrame(tick);
      }
      requestAnimationFrame(tick);
    });
  }, { threshold: 0.5 });

  document.querySelectorAll('.about-stat-v').forEach(el => counterObserver.observe(el));
})();

// ---------- Efeito "decriptografando" no título do hero ----------
function scrambleText(el, duration = 800) {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ01#*';
  const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
  const nodes = [];
  let n;
  while ((n = walker.nextNode())) nodes.push(n);

  nodes.forEach(node => {
    const original = node.textContent;
    const len = original.length;
    const totalFrames = Math.round(duration / 30);
    let frame = 0;

    const interval = setInterval(() => {
      frame++;
      const revealCount = Math.floor((frame / totalFrames) * len);
      let out = '';
      for (let i = 0; i < len; i++) {
        out += (original[i] === ' ' || i < revealCount) ? original[i] : chars[Math.floor(Math.random() * chars.length)];
      }
      node.textContent = out;
      if (frame >= totalFrames) {
        node.textContent = original;
        clearInterval(interval);
      }
    }, 30);
  });
}

function runHeroScramble() {
  const heroH1 = document.querySelector('.hero h1');
  if (!heroH1 || prefersReducedMotion) return;
  scrambleText(heroH1, 800);

  setTimeout(() => {
    heroH1.classList.add('glitching');
    setTimeout(() => heroH1.classList.remove('glitching'), 350);
  }, 850);
}
window.addEventListener('bootDone', runHeroScramble);

